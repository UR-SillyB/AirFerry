/**
 * Post-build: inline the Vite standalone output into a single self-contained
 * `index.html` that runs when double-clicked under `file://`.
 *
 * Input  (dist-standalone/):
 *   index.js                       — IIFE main bundle (transfer_engine WASM
 *                                    already inlined as base64 by Vite)
 *   web.css                        — styles
 *   assets/compress.worker-*.js    — worker chunk (fully self-contained)
 *
 * Output (dist-standalone/index.html):
 *   A single HTML file whose sender favicon is embedded as a data URL. Before
 *   the main bundle runs, globals are defined so the shared sender source
 *   picks the file://-safe code paths:
 *     globalThis.__AIRFERRY_STANDALONE__ = true   (gate flag)
 *     globalThis.__WORKER_CODE__          = "..."  (worker source as a string;
 *                                          options.tsx wraps it in a Blob URL)
 */
const fs = require("fs")
const path = require("path")

const root = path.resolve(__dirname, "..")
const outDir = path.join(root, "dist-standalone")

// Locate the intermediate artifacts Vite produced.
const mainJs = path.join(outDir, "index.js")
const cssFile = path.join(outDir, "web.css")
const senderFavicon = path.join(root, "public", "favicon-sender.png")

for (const f of [mainJs, cssFile, senderFavicon]) {
  if (!fs.existsSync(f)) {
    console.error(`\n✖ Missing build artifact: ${path.relative(root, f)}\n  Run "vite build --config vite.standalone.config.ts" first.\n`)
    process.exit(1)
  }
}

// The worker chunk has a content-hashed name (e.g. compress.worker-BcBCKaY9.js).
const assetsDir = path.join(outDir, "assets")
const workerFile = fs.readdirSync(assetsDir).find((n) => /^compress\.worker-.*\.js$/.test(n))
if (!workerFile) {
  console.error(`\n✖ Missing worker chunk in ${path.relative(root, assetsDir)}\n`)
  process.exit(1)
}
const workerPath = path.join(assetsDir, workerFile)

const mainJsCode = fs.readFileSync(mainJs, "utf8")
const cssCode = fs.readFileSync(cssFile, "utf8")
const senderFaviconB64 = fs.readFileSync(senderFavicon).toString("base64")

// The worker chunk is ES-formatted and may contain `import.meta.url`
// expressions generated by Vite/wasm glue. Under file:// we load the worker
// from a Blob URL as a CLASSIC worker (best cross-browser support).
const workerCodeRaw = fs.readFileSync(workerPath, "utf8").replace(
  /import\.meta\.url/g,
  '"blob:standalone"'
)

function safeForInlineScript(code) {
  return code.replace(/<\/script>/gi, "<\\/script>").replace(/<!--/g, "<\\!--")
}

const prelude = [
  `globalThis.process=globalThis.process||{env:{NODE_ENV:"production"}};`,
  `globalThis.__AIRFERRY_STANDALONE__=true;`,
  `globalThis.__WORKER_CODE__=${JSON.stringify(workerCodeRaw)};`,
].join("\n")

const html = `<!DOCTYPE html>
<html lang="zh-CN">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<meta name="description" content="通过屏幕二维码视频流，无网传输文件到手机。单文件版，双击即可运行。">
<link rel="icon" type="image/png" href="data:image/png;base64,${senderFaviconB64}">
<title>AirFerry · 无网文件传输</title>
<style>
${cssCode}
</style>
</head>
<body>
<div id="root"></div>
<script>
${safeForInlineScript(prelude)}
${safeForInlineScript(mainJsCode)}
</script>
</body>
</html>
`

const outHtml = path.join(outDir, "index.html")
fs.writeFileSync(outHtml, html)

// Clean up intermediate files.
for (const f of [mainJs, cssFile]) {
  try {
    fs.unlinkSync(f)
  } catch (_) {}
}
for (const f of [
  "airferry_zxing.js",
  "airferry_zxing.wasm",
  "favicon-sender.png",
  "favicon-receiver.png",
]) {
  try {
    fs.unlinkSync(path.join(outDir, f))
  } catch (_) {}
}
try {
  fs.rmSync(assetsDir, { recursive: true, force: true })
} catch (_) {}

const finalSize = fs.statSync(outHtml).size
const workerKb = Math.round(Buffer.byteLength(workerCodeRaw, "utf8") / 1024)
console.log(`\n✓ Standalone single-file HTML written:`)
console.log(`    ${path.relative(root, outHtml)}  (${Math.round(finalSize / 1024)} KB)`)
console.log(`    inlined: worker (${workerKb} KB)`)
console.log(`    transfer_engine WASM already inlined by Vite into the JS bundle.`)
console.log(`    cleaned ${path.relative(root, outDir)} intermediates (index.js / web.css / assets/)\n`)
